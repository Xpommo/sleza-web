const BOOKING_BY_SPHERE = {
  school: ['Записать на занятие', 'запись на занятие'],
  kids: ['Записать на занятие', 'запись на занятие'],
  beauty: ['Записать на приём', 'запись на приём'],
  medicine: ['Записать на приём', 'запись на приём'],
  it: ['Записать на демонстрацию или созвон', 'запись на демонстрацию продукта или созвон'],
  manuf: ['Записать на встречу', 'запись на встречу'],
};
export function purposeLabel(value, sphere) {
  if (value === 'booking' && BOOKING_BY_SPHERE[sphere]) return BOOKING_BY_SPHERE[sphere][0];
  if (value === PROMO_PURPOSE.value) return PROMO_PURPOSE.label;
  return PURPOSES.find((p) => p.value === value)?.label || '';
}
export function bookingText(sphere) {
  return BOOKING_BY_SPHERE[sphere]?.[1] || 'запись на приём, занятие или встречу';
}

